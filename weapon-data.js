// Pick the weapon that best fits a description. Used by the forge when a move
// asks for, say, "a heavy two-handed axe" instead of naming a specific sprite.
export function findWeapon(query = "") {
  const text = String(query).toLowerCase();
  if (WEAPON_BY_ID.has(text)) return WEAPON_BY_ID.get(text);
  const scored = WEAPON_ENTRIES.map((weapon) => {
    let score = 0;
    if (text.includes(weapon.weaponClass)) score += 6;
    if (text.includes(weapon.tier)) score += 3;
    for (const word of weapon.family.split("_")) if (word.length > 2 && text.includes(word)) score += 2;
    if (text.includes("two") && weapon.grip === "two-hand") score += 2;
    if (text.includes("one") && weapon.grip === "one-hand") score += 2;
    return { weapon, score };
  }).sort((a, b) => b.score - a.score);
  return scored[0]?.score > 0 ? scored[0].weapon : null;
}
