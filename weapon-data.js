// The motions a weapon can be swung with. Each one is a different arc through
// the attack's active frames, so a stab does not read like a slash.
export const WEAPON_MOTIONS = [
  "swipe",      // a horizontal slash
  "arc",        // a crescent that rises and falls
  "overhead",   // chopped down from above the head
  "stab",       // a straight forward thrust
  "dive-stab",  // point-down thrust, on the ground or dropping out of the air
  "spin",       // spun flat around the body
  "jump-spin",  // spun overhead while airborne
  "sweep",      // low, along the floor
  "throw",      // released forward, tumbling
  "spin-throw", // wound up in a spin, then released
  "shoot"       // levelled and fired
];

